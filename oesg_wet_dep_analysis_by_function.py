    monthly_df = pd.concat(monthly_dfs, ignore_index=True)

    # --- 5. Seasonal Mann-Kendall trend ---
    def compute_smk_annual_trends(
        monthly_df,
        variables=['concentration','deposition','mm'],
        alpha=0.05,
        mode="pre",
        significance_thresholds=None
    ):
        """
        Compute seasonal Mann–Kendall trends and annual slope for multiple variables, by site,
        and add alternate significance criteria.

        Returns a DataFrame including both significance tests.
        """
        results = []
        if significance_thresholds is None:
            significance_thresholds = {}

        for site, site_df in monthly_df.groupby('site'):
            site_df = site_df.copy()
            # Apply cutoff using datetime column
            if mode == "pre":
                site_df = site_df[site_df["datetime"] < cutoff]
            elif mode == "post":
                site_df = site_df[site_df["datetime"] >= cutoff]

            site_df['season'] = site_df['month']

            if len(site_df) < 12:
                continue

            for var in variables:
                var_series = site_df[var].dropna()
                if len(var_series) < 12:
                    continue

                try:
                    res = mk.seasonal_test(var_series.values, period=12)
                except Exception as e:
                    print(f"❌ Error processing {site} {var}: {e}")
                    continue

                annual_slope = res.slope * 12

                # Null-hypothesis significance test
                p_significant = res.p < alpha

                # Alternate numeric threshold significance test
                threshold_value = significance_thresholds.get(var)
                alt_significant = None
                if threshold_value is not None:
                    alt_significant = abs(annual_slope) >= threshold_value
                else:
                    alt_significant = p_significant  # fallback

                results.append({
                    "site": site_name,
                    "mode": mode,
                    "trend": res.trend,
                    "p_value": res.p,
                    "significant": res.p < 0.05,
                    "seasonal_slope_per_month": res.slope,
                    "annual_slope": res.slope * 12,
                    "n": len(site_df),
                    "years_span": span_years,
                    "start": site_df["datetime"].min(),
                    "end": site_df["datetime"].max()
                })
        return pd.DataFrame(results)
    
    # --- 6. Run the SMK analysis ---
    # set thresholds as the median of the annual slopes from the original MK analysis
    thresholds = {
        'mm': 8,            # mm/year slope threshold
        'deposition': 13,    # deposition/year slope threshold
        'concentration': 0.6 # concentration/year slope threshold
    }

    pre_smk_df = compute_smk_annual_trends(monthly_df, mode="pre", significance_thresholds=thresholds)
    post_smk_df = compute_smk_annual_trends(monthly_df, mode="post", significance_thresholds=thresholds)

    # Merge side-by-side
    comparison_df = pd.merge(
        pre_smk_df,
        post_smk_df,
        on="site",
        suffixes=("_pre2013", "_post2013")
    )

    print(comparison_df.head())
    comparison_df.to_csv(r'\\econm3hwvfsp008.ncr.int.ec.gc.ca\arqp_data\Projects\OnGoing\Mercury\HGEE-Minamata\Results and Plots\comparison_df.csv', index=False)


