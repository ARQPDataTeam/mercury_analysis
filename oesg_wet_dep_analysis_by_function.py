def wet_dep_insert(sql_engine):
    wet_dep_sites_df = pd.read_csv(r'\\econm3hwvfsp008.ncr.int.ec.gc.ca\arqp_data\Projects\OnGoing\Mercury\HGEE-Minamata\Data\US\mdn.csv')

    # insert missing latdecd and londecd into the hgee_active table
    with sql_engine.connect() as conn:
        metadata = MetaData()
        hgee_active = Table('hgee_active', metadata, autoload_with=sql_engine)

        for idx, row in wet_dep_sites_df.iterrows():
            site = row['site']
            latdecd = row['latdecd']
            londecd = row['londecd']

            stmt = (
                update(hgee_active)
                .where(hgee_active.c.site == site)
                .values(latdecd=latdecd, londecd=londecd)
            )

            try:
                result = conn.execute(stmt)
                if result.rowcount > 0:
                    print(f"Updated site {site} with lat: {latdecd}, lon: {londecd}")
                else:
                    print(f"No matching site found for {site}.")
            except SQLAlchemyError as e:
                print(f"Error updating site {site}: {e}")

