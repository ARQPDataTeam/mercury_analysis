    flags_to_exclude = ['C','890','780','783','999','899']
    mercury_df.loc[mercury_df['flag_orig'].isin(flags_to_exclude), ['mm','concentration','deposition']] = pd.NA

    # Drop rows missing any key variable
    # mercury_df = mercury_df.dropna(subset=['mm','concentration','deposition'])

    # # Ensure consistent datetime format
    # for col in ['start_dt','end_dt','datetime']:
    #     mercury_df[col] = pd.to_datetime(mercury_df[col], errors='coerce')

    # print (mercury_df['start_dt'])
    
    # --- 2. Monthly aggregation function (prorated) ---
    def monthly_aggregates(df, start_col="start_dt", end_col="end_dt", agg_map=None):
        from calendar import monthrange
        import numpy as np
        
        df = df.copy()
        df[start_col] = pd.to_datetime(df[start_col])
        df[end_col] = pd.to_datetime(df[end_col])
        records = []

        for _, row in df.iterrows():
            start = row[start_col]
            end = row[end_col]

            # if row['country'] in ["Canada", "United States"]:
            #     print(f"[DEBUG] Site={row['site']}, Country={row['country']}, Start={start}, End={end}")

            if pd.isna(start) or pd.isna(end) or end <= start:
                continue

            total_days = (end - start).days
            if total_days <= 0:
                continue

            current = start
            while current < end:
                y, m = current.year, current.month
                last_day = pd.Timestamp(year=y, month=m, day=monthrange(y, m)[1])
                seg_end = min(end, last_day + pd.Timedelta(days=1))
                seg_days = (seg_end - current).days

                if end <= start:
                    print(f"Bad interval at {row['site']} ({row['country']}): start={start}, end={end}")
                    continue

                if seg_days > 0:
                    rec = {"year": y, "month": m, "days": seg_days}
                    for col, how in agg_map.items():
                        val = row[col]
                        if pd.isna(val):
                            continue
                        if how == "sum":
                            rec[col] = (val / total_days) * seg_days
                        elif how == "prorated_mean":
                            rec[col] = (val / total_days) * seg_days
                            rec[f"{col}_weight"] = seg_days
                        elif how == "pwc":
                            if pd.isna(row["mm"]):
                                continue
                            prorated_mm = (row["mm"] / total_days) * seg_days
                            rec[f"{col}_num"] = val * prorated_mm
                            rec[f"{col}_den"] = prorated_mm
                    records.append(rec)
                current = seg_end

        prorated = pd.DataFrame(records)
        if prorated.empty:
            return pd.DataFrame(columns=["year","month"] + list(agg_map.keys()))

        def agg_func(g):
            out = {}
            for col, how in agg_map.items():
                if how == "sum":
                    out[col] = g[col].sum()
                elif how == "prorated_mean":
                    if f"{col}_weight" in g:
                        out[col] = np.average(g[col], weights=g[f"{col}_weight"])
                    else:
                        out[col] = g[col].mean()
                elif how == "pwc":
                    num = g[f"{col}_num"].sum()
                    den = g[f"{col}_den"].sum()
                    out[col] = num / den if den > 0 else pd.NA
            return pd.Series(out)

        out = prorated.groupby(["year","month"]).apply(agg_func, include_groups=False).reset_index()
        out["datetime"] = pd.to_datetime(out["year"].astype(str) + "-" + out["month"].astype(str) + "-15")
        return out

    # --- 3. Aggregation map ---
    agg_map = {
        "mm": "sum",
        "deposition": "prorated_mean",
        "concentration": "pwc"
    }

