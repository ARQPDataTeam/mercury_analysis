    def normalize_flag(flag_value):
        """Convert erroneous decimal flags into 3-digit strings."""
        if pd.isna(flag_value):
            return None
        flag_int = int(float(flag_value) * 1000)
        return str(flag_int).zfill(3)[:3]


    def map_flag_des(flag_orig, flag_df):
        """Map numeric flag to descriptive flag."""
        try:
            return flag_df.loc[flag_df.index == flag_orig, 'flag_des'].iloc[0]
        except IndexError:
            return None


    def determine_flag_orig(row, flag_df):
        """Determine preferred flag_orig using M1/M2/V0 priority, including single 'flag' column."""
        flags = []

        # Scenario 1: separate flag_mm / flag_Hg columns
        if 'flag_mm' in row and pd.notna(row['flag_mm']):
            flags.append(normalize_flag(row['flag_mm']))
        if 'flag_Hg' in row and pd.notna(row['flag_Hg']):
            flags.append(normalize_flag(row['flag_Hg']))

        # Scenario 2: single 'flag' column exists
        if not flags and 'flag' in row and pd.notna(row['flag']):
            flags.append(normalize_flag(row['flag']))

        if not flags:
            return None

        # Map to descriptive flags
        flag_map = {f: map_flag_des(f, flag_df) for f in flags}

        # Scenario 1 priority logic: M1 > M2 > fallback
        for f, des in flag_map.items():
            if des == 'M1':
                return f
        for f, des in flag_map.items():
            if des == 'M2':
                return f

        # Fallback: just return the first flag
        return flags[0]

