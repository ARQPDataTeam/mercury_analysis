def monthly_averaging():
    def monthly_precip_stats(df, start_col, end_col, mm_col, conc_col, dep_col, flag_col, site_col=None):
        """
        Calculate monthly precipitation stats for each site:
        - Weighted mean precipitation (mm_mean)
        - Precipitation-weighted mean concentration (pwc)
        - Weighted mean deposition (dep_mean)
        Handles intervals that straddle month boundaries.

        Parameters:
            df: pd.DataFrame
            start_col, end_col: str - datetime columns
            mm_col: str - precipitation column
            conc_col: str - concentration column
            dep_col: str - deposition column
            flag_col: str - flag column for filtering
            site_col: str or None - site column if multiple sites

        Returns:
            pd.DataFrame: site (if given), month, mm_mean, pwc, dep_mean
        """

        all_rows = []

        # Filtering step

        # read in the csv file for flag mapping
        flag_df = pd.read_csv(r'\\econm3hwvfsp008.ncr.int.ec.gc.ca\arqp_data\Projects\OnGoing\Mercury\HGEE-Minamata\flag_mapping.csv')

       # Select Project_flag values where DES_flag is in ['M1', 'M2']
        flags_to_exclude = flag_df.loc[flag_df['DES_flag'].isin(['M1', 'M2']), 'Project_flag'] \
            .astype(str) \
            .str.strip() \
            .tolist()

        print(flags_to_exclude)
        df[flag_col] = df[flag_col].astype(str).str.strip()

        # remove the flagged values
        df.loc[df[flag_col].isin(flags_to_exclude), [mm_col, conc_col, dep_col]] = pd.NA

        # remove negative values
        df[[mm_col, conc_col, dep_col]] = df[[mm_col, conc_col, dep_col]].mask(df[[mm_col, conc_col, dep_col]] < 0, pd.NA)



        for _, row in df.iterrows():
            start = pd.to_datetime(row[start_col])
            end = pd.to_datetime(row[end_col])
            mm = row[mm_col]
            conc = row[conc_col]
            dep = row[dep_col]

            if pd.isna(mm) or mm <0:
                continue
            elif pd.isna(conc) or conc <0:
                continue
            elif  pd.isna(dep) or dep <0:
                continue

            months = pd.date_range(start=start.normalize(), end=end.normalize(), freq='MS')
            if len(months) == 0:
                months = [start.normalize()]

            split_points = [start] + list(months[1:]) + [end]

            for i in range(len(split_points) - 1):
                seg_start = split_points[i]
                seg_end = split_points[i + 1]
                if seg_end > end:
                    seg_end = end

                duration = (seg_end - seg_start).total_seconds()
                total_duration = (end - start).total_seconds()
                if total_duration == 0:
                    weight = 1.0
                else:
                    weight = duration / total_duration

                month = seg_start.to_period('M').start_time

                row_data = {
                    'month': month,
                    'mm_segment': mm * weight,
                    'conc_segment': conc if pd.notna(conc) else np.nan,
                    'dep_segment': dep if pd.notna(dep) else np.nan,
                    'duration': duration,
                    'weight': weight
                }
                if site_col:
                    row_data['site'] = row[site_col]

                all_rows.append(row_data)

        seg_df = pd.DataFrame(all_rows)

        group_cols = ['month']
        if site_col:
            group_cols = ['site'] + group_cols

        monthly = seg_df.groupby(group_cols).agg(
            mm_sum=('mm_segment', 'sum'),
            mm_duration_sum=('duration', 'sum'),
            conc_mm_sum=('mm_segment', lambda x: np.nansum(x * seg_df.loc[x.index, 'conc_segment'])),
            mm_sum_for_conc=('mm_segment', lambda x: np.nansum(x[seg_df.loc[x.index, 'conc_segment'].notna()])),
            dep_sum=('dep_segment', lambda x: np.nansum(x * seg_df.loc[x.index, 'weight'])),
            weight_sum=('weight', 'sum')
        ).reset_index()

        # Final calculations
        monthly['mm_mean'] = monthly['mm_sum'] / monthly['weight_sum']        # Weighted mean precipitation
        monthly['pwc'] = monthly['conc_mm_sum'] / monthly['mm_sum_for_conc']  # Precipitation-weighted concentration
        monthly['dep_mean'] = monthly['dep_sum'] / monthly['weight_sum']     # Weighted mean deposition

        return monthly[[*group_cols, 'mm_mean', 'pwc', 'dep_mean']]

