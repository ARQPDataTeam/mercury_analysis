    # split up the dataframe by site and then do 4 side-by-side MK trends for each season for each site
    def mann_kendall_by_site_season(df, value_cols):
        """
        Runs pymannkendall.original_test for each site and calendar month for specified value columns.

        Parameters:
            df: pd.DataFrame containing at least ['site','month'] + value columns
            value_cols: list of columns to test (e.g. ['mm_mean','pwc','dep_mean'])

        Returns:
            pd.DataFrame with Mann-Kendall results for each site/month/value_col
        """

        results = []

        for site, site_df in df.groupby('site'):
            # print (site)
            for season_num, season_df in site_df.groupby('season'):
                season_df_sorted = season_df.sort_values(by='season')

                for col in value_cols:
                    series = season_df_sorted[col].dropna()
                    # print (series.head())

                    # determine an annual average for the first valid year of data
                    # Keep only valid numeric values
                    valid_series = series[(pd.notna(series)) & (series != 0)]

                    if valid_series.empty:
                        first_year_mean = np.nan
                    else:
                        first_year_mean = valid_series.iloc[:4].mean()
                        # print (f"First year mean for {site} {var} in {first_year}: {first_year_mean}")


                    if len(series) >= 3:  # mk requires at least 3 data points
                        test_result = mk.original_test(series)

                        results.append({
                            'site': site,
                            'season': season_num,
                            'variable': col,
                            'trend': test_result.trend,
                            'h': test_result.h,
                            'p': test_result.p,
                            'z': test_result.z,
                            'Tau': test_result.Tau,
                            's': test_result.s,
                            'var_s': test_result.var_s,
                            'slope': test_result.slope/first_year_mean*100,
                            'intercept': test_result.intercept
                        })

        return pd.DataFrame(results)


