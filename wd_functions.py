def wd_check():
    # do a check for issues in the wet dep data
    # read in the wet dep data
    wd_data_path = r'\\econm3hwvfsp008.ncr.int.ec.gc.ca\arqp_data\Projects\OnGoing\Mercury\HGEE-Minamata\Results and Plots\wd_additional_output.csv'
    wd_df = pd.read_csv(wd_data_path, encoding='utf-8')

    # print the length of the dataframe
    print(f"Length of wet dep dataframe: {len(wd_df)}")


    # print(f"Number of missing site names: {len(missing_sites)}")
    # check for repeat combinations of site datetime
    repeat_combinations = wd_df[wd_df.duplicated(subset=['site', 'datetime'], keep=False)]  
    print(f"Number of repeat site-datetime combinations: {len(repeat_combinations)}")
    # print which sites and datetimes are in the repeat combinations subset
    if not repeat_combinations.empty:
        print("Sites with repeat combinations:")
        print(repeat_combinations[['site', 'datetime']])


    # Only consider rows with valid data
    mask_valid = (wd_df['precipitation'] != -999) & (wd_df['concentration'] != -999)&(wd_df['project'] == 'MDN')

    # Calculate expected deposition
    expected_dep = wd_df.loc[mask_valid, 'precipitation'] * wd_df.loc[mask_valid, 'concentration']

    # replace wd dataframe deposition column with expected deposition for valid rows
    wd_df.loc[mask_valid, 'deposition'] = expected_dep


    # Flag rows where deposition differs by more than 10%
    tolerance = 0.10  # 10%
    nonsensical_mask = mask_valid & (
        np.abs(wd_df['deposition'] - expected_dep) / expected_dep > tolerance
    )

    # Extract problematic rows
    nonsensical_dep = wd_df[nonsensical_mask]  

    # print description of the nonsensical deposition values
    print("Description of nonsensical deposition values:")  
    print(nonsensical_dep.describe())

    # output the nonsensical deposition values to a csv
    nonsensical_dep.to_csv(r'\\econm3hwvfsp008.ncr.int.ec.gc.ca\arqp_data\Projects\OnGoing\Mercury\HGEE-Minamata\Results and Plots\wd_nonsensical_deposition_2025-10-28.csv', index=False, encoding='utf-8')

    # replace wd_df['deposition'] where wd_df['deposition']==0 and != -999 with -999
    wd_df.loc[(wd_df['deposition'] == 0) & (wd_df['precipitation'] ==0), ['deposition','flag_des']] = [-999, 'M2']    

    # check for bad values not flagged as M1 or M2
    bad_values = wd_df[~wd_df['flag_des'].isin(['M1', 'M2'])]
    bad_values = bad_values[
        (((bad_values['concentration'] <= 0) & (bad_values['concentration'] != -999)) |
        ((bad_values['deposition'] <= 0) & (bad_values['deposition'] != -999)))]
    
    print(f"Number of bad values not flagged as M1 or M2: {len(bad_values)}")

    # round concentration and deposition to 3 decimal places
    wd_df['concentration'] = wd_df['concentration'].round(3)
    wd_df['deposition'] = wd_df['deposition'].round(3)
    wd_df['precipitation'] = wd_df['precipitation'].round(3)


    # print the bad values to a csv
    wd_df.to_csv(r'\\econm3hwvfsp008.ncr.int.ec.gc.ca\arqp_data\Projects\OnGoing\Mercury\HGEE-Minamata\Results and Plots\wd_output_2025-11-05.csv', index=False, encoding='utf-8')

