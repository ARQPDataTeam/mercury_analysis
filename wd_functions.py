def annual_summary(sql_engine):

    def annual_slope_from_monthly(monthly_slopes, month_counts=None):
        """
        Compute annual slope as a weighted average of monthly slopes.
        Handles NaNs and non-finite values robustly.
        """
        # Convert list input to dict
        if isinstance(monthly_slopes, list):
            slopes = {i + 1: monthly_slopes[i] for i in range(len(monthly_slopes))}
        else:
            slopes = dict(monthly_slopes)

        # Default days per month (leap year)
        if month_counts is None:
            month_counts = {m: calendar.monthrange(2000, m)[1] for m in range(1, 13)}

        # Filter only valid numeric slopes
        valid_months = {
            m: float(v)
            for m, v in slopes.items()
            if pd.notna(v) and np.isfinite(v)
        }

        if not valid_months:
            return np.nan

        total_days = sum(month_counts[m] for m in valid_months.keys())
        if total_days == 0:
            print ("Total days is zero, cannot compute annual slope.")
            return np.nan

        weighted_sum = sum(valid_months[m] * month_counts[m] for m in valid_months)
        annual_slope = weighted_sum / total_days
        # print ("Annual slope calculated:", annual_slope)
        return annual_slope

    def annual_mannkendall_summary(mk_df):
        """
        Computes annual Mann-Kendall summary from monthly MK results.

        mk_df: pd.DataFrame with columns:
            ['site', 'variable', 'month', 'Tau', 'p', 'slope']

        Returns:
            pd.DataFrame with annual trends for each site and variable.
        """

        results = []

        for (site, variable), group in mk_df.groupby(['site', 'variable']):
            # print (site, variable)
            taus = group['Tau'].dropna().values
            ps = group['p'].dropna().values
            slopes = group['slope'].dropna().values

            if len(taus) == 0:
                continue

            # 1. Mean Tau (direction + strength)
            annual_tau = np.mean(taus)

            # 2. Mean slope
            annual_slope = annual_slope_from_monthly(
                {row['month']: row['slope'] for _, row in group.iterrows()}
            )


        # 3. Combine p-values using Fisher’s method
            if len(ps) > 0:
                chi_stat = -2 * np.sum(np.log(ps))
                combined_p = chi2.sf(chi_stat, 2 * len(ps))  # survival function (1-CDF)
            else:
                combined_p = np.nan

            # Determine direction of trend from Tau
            if annual_slope > 0 and combined_p < 0.05:
                annual_trend = "INCREASING"
            elif annual_slope < 0 and combined_p < 0.05:
                annual_trend = "DECREASING"
            else:
                annual_trend = "NO TREND"

            results.append({
                "SITE": site,
                "VARIABLE": variable,
                "ANNUAL SLOPE": annual_slope,
                "P VALUE": combined_p,
                "ANNUAL TREND": annual_trend
            })

        return pd.DataFrame(results)

